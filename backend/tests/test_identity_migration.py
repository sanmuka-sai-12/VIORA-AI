@pytest.mark.postgres
def test_existing_source_survives_migration_round_trip(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    raw_url = os.environ.get("VIORA_TEST_DATABASE_URL")
    if not raw_url:
        pytest.skip("Dedicated PostgreSQL integration database required")
    schema = f"migration_{uuid4().hex}"
    url = make_url(raw_url)
    scoped_url = url.update_query_dict({"options": f"-csearch_path={schema}"})
    monkeypatch.setenv("DATABASE_URL", scoped_url.render_as_string(hide_password=False))
    monkeypatch.setenv(
        "MIGRATION_DATABASE_URL", scoped_url.render_as_string(hide_password=False)
    )
    admin = create_engine(url)
    scoped = create_engine(scoped_url)
    config = Config(str(ROOT / "alembic.ini"))
    tenant, source = uuid4(), uuid4()
    try:
        with admin.begin() as connection:
            connection.execute(CreateSchema(schema))
        try:
            command.upgrade(config, BASELINE)
            with scoped.begin() as connection:
                connection.execute(
                    text(
                        "INSERT INTO sources (tenant_id, source_id, title) VALUES (:tenant, :source, 'Legacy')"
                    ),
                    {"tenant": tenant, "source": source},
                )
            command.upgrade(config, "head")
            command.check(config)
            with scoped.connect() as connection:
                assert (
                    connection.scalar(
                        text(
                            "SELECT active FROM institutions WHERE tenant_id = :tenant"
                        ),
                        {"tenant": tenant},
                    )
                    is False
                )
            command.downgrade(config, BASELINE)
            with scoped.connect() as connection:
                assert set(inspect(connection).get_table_names()) == {
                    "alembic_version",
                    "sources",
                }
                assert connection.execute(
                    text("SELECT tenant_id, source_id, title FROM sources")
                ).one() == (tenant, source, "Legacy")
            command.upgrade(config, "head")
            command.check(config)
        finally:
            scoped.dispose()
            with admin.begin() as connection:
                connection.execute(DropSchema(schema, cascade=True))
    finally:
        admin.dispose()


@pytest.mark.postgres
def test_embedding_fallback_and_drift_detection_disposable_postgres(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    raw_url = os.environ.get("VIORA_TEST_DATABASE_URL")
    if not raw_url:
        pytest.skip("Dedicated PostgreSQL integration database required")
    url = make_url(raw_url)
    db_name = f"viora_mig_chk_{uuid4().hex[:12]}"
    disposable_url = url.set(database=db_name)
    disposable_str = disposable_url.render_as_string(hide_password=False)

    admin = create_engine(url, isolation_level="AUTOCOMMIT")
    disposable = create_engine(disposable_url)
    config = Config(str(ROOT / "alembic.ini"))
    monkeypatch.setenv("DATABASE_URL", disposable_str)
    monkeypatch.setenv("MIGRATION_DATABASE_URL", disposable_str)

    try:
        with admin.connect() as connection:
            connection.connection.driver_connection.execute(
                sql.SQL("CREATE DATABASE {}").format(sql.Identifier(db_name))
            )
        try:
            command.upgrade(config, "head")
            command.check(config)

            with disposable.connect() as connection:
                has_pgvector = bool(
                    connection.scalar(
                        text("SELECT 1 FROM pg_extension WHERE extname = 'vector'")
                    )
                )

            if has_pgvector:
                # Replacing vector(384) with double precision[] while pgvector is active MUST be flagged as drift.
                with disposable.begin() as connection:
                    connection.execute(text("DROP INDEX IF EXISTS ix_kic_embedding_hnsw"))
                    connection.execute(
                        text("ALTER TABLE knowledge_index_chunks DROP COLUMN embedding")
                    )
                    connection.execute(
                        text(
                            "ALTER TABLE knowledge_index_chunks ADD COLUMN embedding double precision[]"
                        )
                    )
                with pytest.raises(AutogenerateDiffsDetected):
                    command.check(config)

                # Removing pgvector extension leaves the intentional non-pgvector 0012 fallback state.
                with disposable.begin() as connection:
                    connection.execute(text("DROP EXTENSION vector"))

            # In non-pgvector PostgreSQL (such as CI postgres:17.12), double precision[] matches 0012 cleanly.
            command.check(config)

            # Real schema drift on embedding or other columns MUST still fail command.check.
            with disposable.begin() as connection:
                connection.execute(
                    text("ALTER TABLE knowledge_index_chunks ALTER COLUMN embedding TYPE text")
                )
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(config)

            with disposable.begin() as connection:
                connection.execute(
                    text(
                        "ALTER TABLE knowledge_index_chunks ALTER COLUMN embedding TYPE double precision[] USING NULL"
                    )
                )
                connection.execute(
                    text("ALTER TABLE knowledge_index_chunks ALTER COLUMN chunk_index TYPE bigint")
                )
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(config)
        finally:
            disposable.dispose()
            with admin.connect() as connection:
                connection.connection.driver_connection.execute(
                    sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(
                        sql.Identifier(db_name)
                    )
                )
    finally:
        admin.dispose()
